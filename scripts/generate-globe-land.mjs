const toPoly = (flat) => {
  const out = [];
  for (let i = 0; i < flat.length; i += 2) out.push([flat[i], flat[i + 1]]);
  return out;
};

const prep = (flat) => {
  const poly = toPoly(flat);
  let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
  for (const [x, y] of poly) {
    if (x < minLon) minLon = x;
    if (x > maxLon) maxLon = x;
    if (y < minLat) minLat = y;
    if (y > maxLat) maxLat = y;
  }
  return { poly, minLon, maxLon, minLat, maxLat };
};

const inside = (shape, lon, lat) => {
  if (lon < shape.minLon || lon > shape.maxLon || lat < shape.minLat || lat > shape.maxLat) return false;
  const { poly } = shape;
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};

export function buildRows() {
  const landShapes = Object.values(land).map(prep);
  const waterShapes = Object.values(water).map(prep);
  const isLand = (lon, lat) =>
    landShapes.some((s) => inside(s, lon, lat)) && !waterShapes.some((s) => inside(s, lon, lat));

  const rows = [];
  for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
    const la = Math.round(lat * 10) / 10;
    const n = Math.max(1, Math.round((360 * Math.cos((la * Math.PI) / 180)) / STEP));
    const flags = [];
    for (let i = 0; i < n; i++) flags.push(isLand(-180 + ((i + 0.5) * 360) / n, la));
    // Run-length encode: [skip, land, skip, land, ...] starting with a (possibly zero) water run.
    const runs = [];
    let cur = false;
    let count = 0;
    for (const f of flags) {
      if (f === cur) count++;
      else { runs.push(count); cur = f; count = 1; }
    }
    runs.push(count);
    if (flags.some(Boolean)) rows.push([la, n, ...runs]);
  }
  return rows;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rows = buildRows();
  const body = rows.map((r) => `  [${r.join(',')}]`).join(',\n');
  const out =
    '// GENERATED by scripts/generate-globe-land.mjs - do not edit by hand.\n' +
    '// Each row: [latitude, dotsInRow, waterRun, landRun, waterRun, landRun, ...]\n\n' +
    `export const GLOBE_LAND_ROWS = [\n${body},\n];\n`;
  writeFileSync(new URL('../src/data/globeLand.js', import.meta.url), out);
  let dots = 0;
  for (const [, , ...runs] of rows) for (let i = 1; i < runs.length; i += 2) dots += runs[i];
  console.log(`wrote ${rows.length} rows, ${dots} land dots, ${out.length} bytes`);
}

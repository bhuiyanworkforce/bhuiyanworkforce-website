#!/usr/bin/env node
// Static page generator. Replaces prerender.mjs (Puppeteer).
//
// Run after `vite build` (client -> dist/) and `vite build --ssr` (-> dist-ssr/).
// For every page in src/routes.js it renders the React tree to a string with
// react-dom/server, injects the page's own <head> and writes dist/<path>/index.html.
// Also writes dist/404.html and dist/sitemap.xml.
//
// dist-ssr/entry-server.js must export:
//   render(path)  -> HTML string for <div id="root"> (path is the URL pathname;
//                    an unknown path must render the NotFound page)
//   data          -> { country(slug), service(slug), post(slug), guide(slug) }

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import '../src/i18n/ar-bundle.js'; // registers the Arabic content that is loaded on demand in the browser
import { listPages } from '../src/routes.js';
import { getPageHead } from '../src/seo/getPageHead.js';
import { headToHtml } from '../src/seo/headHtml.js';
import { buildSitemap } from '../src/seo/sitemap.js';
import { LOCALES } from '../src/i18n/config.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = process.env.DIST_DIR ? path.resolve(process.env.DIST_DIR) : path.join(ROOT, 'dist');
const SSR_ENTRY = process.env.SSR_ENTRY
  ? path.resolve(process.env.SSR_ENTRY)
  : path.join(ROOT, 'dist-ssr', 'entry-server.js');

const ROOT_DIV = '<div id="root"></div>';

// Everything the generated head replaces. Matching is by element kind, so it
// works whether the template still carries the old hand-written tags or not.
const STRIP = [
  /<title>[\s\S]*?<\/title>\s*/gi,
  /<meta\s+name="(?:description|keywords|robots)"[^>]*>\s*/gi,
  /<meta\s+property="og:[^"]*"[^>]*>\s*/gi,
  /<meta\s+name="twitter:[^"]*"[^>]*>\s*/gi,
  /<link\s+rel="canonical"[^>]*>\s*/gi,
  /<link\s+rel="alternate"\s+hreflang[^>]*>\s*/gi,
  /<script\s+type="application\/ld\+json">[\s\S]*?<\/script>\s*/gi,
  /<!--\s*(?:JSON-LD|Open Graph|Twitter|Primary Meta|Canonical)[\s\S]*?-->\s*/gi,
];

export function injectPage(template, head, bodyHtml, ssrPath) {
  if (!template.includes(ROOT_DIV)) throw new Error('template has no empty <div id="root"></div>');
  let html = template;
  for (const re of STRIP) html = html.replace(re, '');
  html = html.replace(/<html[^>]*>/i, `<html lang="${head.lang}" dir="${head.dir}">`);
  const headHtml = headToHtml(head);
  if (html.includes('<!--app-head-->')) html = html.replace('<!--app-head-->', headHtml);
  else html = html.replace('</head>', `${headHtml}\n  </head>`);
  html = html.replace(ROOT_DIV, `<div id="root" data-ssr-path="${ssrPath}">${bodyHtml}</div>`);

  // Self-check: exactly one of each unique head element.
  const count = (re) => (html.match(re) || []).length;
  const expectCanonical = head.canonical ? 1 : 0;
  if (count(/<title>/g) !== 1) throw new Error('expected exactly one <title>');
  if (count(/<link rel="canonical"/g) !== expectCanonical) throw new Error('canonical count wrong');
  if (count(/<meta name="description"/g) !== 1) throw new Error('expected exactly one meta description');
  if (count(/application\/ld\+json/g) !== head.jsonld.length) throw new Error('JSON-LD count wrong');
  return html;
}

function outFile(p) {
  return p === '/' ? path.join(DIST, 'index.html') : path.join(DIST, p.replace(/^\//, ''), 'index.html');
}

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

async function main() {
  const t0 = Date.now();
  const templatePath = path.join(DIST, 'index.html');
  if (!fs.existsSync(templatePath)) throw new Error(`no ${templatePath}; run "vite build" first`);
  if (!fs.existsSync(SSR_ENTRY)) throw new Error(`no ${SSR_ENTRY}; run "vite build --ssr src/entry-server.jsx --outDir dist-ssr" first`);

  // Read the template once: the English homepage overwrites dist/index.html.
  const template = fs.readFileSync(templatePath, 'utf8');
  if (template.includes('data-ssr-path=')) {
    throw new Error('dist/index.html was already generated by a previous run; run "vite build" again to get a clean template');
  }
  const { render, data, getFallbackReport } = await import(pathToFileURL(SSR_ENTRY).href);

  const pages = listPages();
  const failures = [];
  let written = 0;

  for (const page of pages) {
    try {
      const head = getPageHead(page.route, page.lang, data);
      const body = render(page.path);
      if (!body || body.length < 200) throw new Error('rendered body is empty or suspiciously short');
      write(outFile(page.path), injectPage(template, head, body, page.path));
      written += 1;
    } catch (err) {
      failures.push({ path: page.path, message: err.message });
    }
  }

  // 404.html: Cloudflare Pages serves it (with a 404 status) for unknown URLs.
  try {
    const head = getPageHead({ type: 'notfound' }, 'en', data);
    write(path.join(DIST, '404.html'), injectPage(template, head, render('/__404__'), '__404__'));
  } catch (err) {
    failures.push({ path: '404.html', message: err.message });
  }

  write(path.join(DIST, 'sitemap.xml'), buildSitemap(pages));

  console.log(`Generated ${written}/${pages.length} pages + 404.html + sitemap.xml in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  const perLang = Object.keys(LOCALES).map((l) => [l, pages.filter((p) => p.lang === l).length]).filter(([, n]) => n);
  console.log('Pages per language:', perLang.map(([l, n]) => `${l}=${n}`).join(' '));
  // Every place a real language fell back to English (missing translation). Never fails the build.
  const fallbacks = typeof getFallbackReport === 'function' ? getFallbackReport() : [];
  if (fallbacks.length) {
    console.warn(`\nTranslation fallbacks to English: ${fallbacks.length}`);
    const groups = new Map();
    for (const f of fallbacks) {
      const k = `${f.lang} / ${f.kind}`;
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(f.key);
    }
    for (const [k, keys] of groups) console.warn(`  ${k}: ${keys.length} (${keys.slice(0, 6).join(', ')}${keys.length > 6 ? ', ...' : ''})`);
  } else {
    console.log('Translation fallbacks to English: none');
  }

  if (failures.length) {
    console.warn(`\nWARNING: ${failures.length} page(s) failed and were skipped:`);
    for (const f of failures.slice(0, 15)) console.warn(`  ${f.path}: ${f.message}`);
    if (failures.length > 15) console.warn(`  ... and ${failures.length - 15} more`);
  }
  console.log(`Total pages generated: ${written}/${pages.length}. Failed routes: ${failures.length ? failures.map((f) => f.path).join(', ') : 'none'}`);
  // Only the English homepage is fatal: one broken page must not block the deploy.
  if (failures.some((f) => f.path === '/')) {
    console.error('\nFATAL: the English homepage failed to generate.');
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
